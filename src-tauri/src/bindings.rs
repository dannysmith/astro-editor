use tauri_specta::{collect_commands, Builder};

/// Export TypeScript bindings to the frontend (debug mode only)
#[cfg(debug_assertions)]
pub fn export_bindings() {
    let builder = generate_bindings();
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Auto-generated by tauri-specta. DO NOT EDIT.\n\n"),
            "../src/lib/bindings.ts",
        )
        .expect("Failed to export TypeScript bindings");
}

pub fn generate_bindings() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        // Specta refuses to export 64-bit integers because JSON.parse truncates values
        // above 2^53. We need its documented global opt-out for serde_json::Value
        // (frontmatter, recovery data), whose numbers may be i64/u64 and which we can't
        // annotate per field. Runtime is unchanged: IPC is JSON, so these were always JS
        // numbers. It also covers FileEntry.last_modified (Unix seconds). This disables
        // the check for any new u64/i64 field too, so keep large integers out of IPC types.
        .dangerously_cast_bigints_to_number()
        // The frontend never sends these structs to Rust, so separate serialize/
        // deserialize shapes (X_Serialize | X_Deserialize) would add nothing.
        .disable_serde_phases()
        .commands(collect_commands![
            // menu.rs commands
            crate::commands::menu::update_format_menu_state,
            // files.rs commands
            crate::commands::files::read_file,
            crate::commands::files::create_file,
            crate::commands::files::delete_file,
            crate::commands::files::rename_file,
            crate::commands::files::copy_file_to_assets,
            crate::commands::files::parse_markdown_content,
            crate::commands::files::save_markdown_content,
            crate::commands::files::save_recovery_data,
            crate::commands::files::save_crash_report,
            crate::commands::files::read_file_content,
            crate::commands::files::is_path_in_project,
            crate::commands::files::get_relative_path,
            crate::commands::files::resolve_image_path,
            // project.rs commands
            crate::commands::project::select_project_folder,
            crate::commands::project::scan_project,
            crate::commands::project::resolve_file_entry,
            crate::commands::project::load_file_based_collection,
            crate::commands::project::scan_directory,
            crate::commands::project::count_collection_files_recursive,
            crate::commands::project::scan_collection_files_recursive,
            crate::commands::project::new_file_name,
            crate::commands::project::rename_entry,
            // watcher.rs commands
            crate::commands::watcher::start_watching_project,
            crate::commands::watcher::stop_watching_project,
            // preferences.rs commands
            crate::commands::preferences::open_preferences_folder,
            crate::commands::preferences::reset_all_preferences,
            crate::commands::preferences::load_preferences,
            crate::commands::preferences::save_global_settings,
            crate::commands::preferences::open_project,
            crate::commands::preferences::save_project_settings,
            crate::commands::preferences::list_projects,
            crate::commands::preferences::remove_project,
            crate::commands::preferences::relocate_project,
            // quit.rs commands
            crate::commands::quit::quit_app,
            crate::commands::quit::cancel_quit,
            // diagnostics.rs commands
            crate::commands::diagnostics::get_app_version,
            crate::commands::diagnostics::get_platform_info,
            // ide.rs commands
            crate::commands::ide::open_path_in_ide,
            // mdx_components.rs commands
            crate::commands::mdx_components::scan_mdx_components,
            crate::commands::mdx_components::plan_component_import,
            crate::commands::mdx_components::project_dependencies,
            // clipboard.rs commands
            crate::commands::clipboard::copy_text_to_clipboard,
            // updater.rs commands
            crate::commands::updater::fetch_release_notes,
            // fonts.rs commands
            crate::commands::fonts::get_linux_ui_font,
        ])
}

